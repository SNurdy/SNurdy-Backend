-- V66__create_term_id_aliases.sql
-- v1 앱은 V52 V55 에서 소프트삭제된 옛 termId 를 기기에 저장해 두고 마이그레이션 업로드 때 그대로 보낸다
-- 옛 termId 를 대표 termId 로 바꿔 받기 위한 별칭 테이블
-- 744 는 V52 에서 224 로 그 224 는 V55 에서 25 로 합쳐졌으므로 한 번만 찾도록 최종 대표 ID 를 저장한다

CREATE TABLE IF NOT EXISTS term_id_aliases (
                                               alias_term_id     BIGINT      NOT NULL COMMENT '소프트삭제된 옛 term id',
                                               canonical_term_id BIGINT      NOT NULL COMMENT '최종 대표 term id',
                                               source_migration  VARCHAR(10) NOT NULL COMMENT '마지막으로 병합한 마이그레이션 버전',
    created_at        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (alias_term_id),
    INDEX idx_term_id_aliases_canonical (canonical_term_id),
    CONSTRAINT fk_term_id_aliases_alias FOREIGN KEY (alias_term_id) REFERENCES terms(id),
    CONSTRAINT fk_term_id_aliases_canonical FOREIGN KEY (canonical_term_id) REFERENCES terms(id)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

